#!/usr/bin/env python3
"""Prepare pinned, small VAD fixtures on CI only; never fetch ASR/LLM weights.

Published model metadata: https://huggingface.co/ggml-org/whisper-vad
Native format: whisper.cpp v1.8.3/models/convert-silero-vad-to-ggml.py
The official sample is distributed in whisper.cpp; its samples README supplies
no separate recording licence. Preserve upstream MIT notices and provenance.
"""

import argparse
import hashlib
import importlib.util
import io
import json
import os
import struct
import subprocess
import sys
import unittest
import urllib.request
import wave
from pathlib import Path
from unittest.mock import patch

sys.dont_write_bytecode = True


MODEL_REVISION = "9ffd54a1e1ee413ddf265af9913beaf518d1639b"
WHISPER_REVISION = "2eeeba56e9edd762b4b38467bab96c2517163158"
SILERO_REVISION = "be95df9152c0d7618fa1edfeb296fc3dae32376f"
MODEL_NAME = "ggml-silero-v6.2.0.bin"
MODEL_SIZE = 885098
MODEL_SHA256 = "2aa269b785eeb53a82983a20501ddf7c1d9c48e33ab63a41391ac6c9f7fb6987"
SPEECH_SIZE = 352078
SPEECH_SHA256 = "59dfb9a4acb36fe2a2affc14bacbee2920ff435cb13cc314a08c13f66ba7860e"
MODEL_URL = f"https://huggingface.co/ggml-org/whisper-vad/resolve/{MODEL_REVISION}/{MODEL_NAME}"
SPEECH_URL = f"https://raw.githubusercontent.com/ggml-org/whisper.cpp/{WHISPER_REVISION}/samples/jfk.wav"
ASSETS = (
    (MODEL_NAME, MODEL_URL, MODEL_SIZE, MODEL_SHA256),
    ("jfk.wav", SPEECH_URL, SPEECH_SIZE, SPEECH_SHA256),
    ("silero-mit.txt", f"https://raw.githubusercontent.com/snakers4/silero-vad/{SILERO_REVISION}/LICENSE",
     1075, "2e63e9a38b6e8fc0c7bc37ce174caca1862870856c6daf5697cfb785e925520b"),
    ("whisper-mit.txt", f"https://raw.githubusercontent.com/ggml-org/whisper.cpp/{WHISPER_REVISION}/LICENSE",
     1078, "e562a2ddfaf8280537795ac5ecd34e3012b6582a147ef69ba6a6a5c08c84757d"),
)
VAD_SYMBOLS = (
    "whisper_vad_default_context_params", "whisper_vad_default_params",
    "whisper_vad_init_from_file_with_params", "whisper_vad_detect_speech",
    "whisper_vad_n_probs", "whisper_vad_probs", "whisper_vad_segments_from_probs",
    "whisper_vad_segments_from_samples", "whisper_vad_segments_n_segments",
    "whisper_vad_segments_get_segment_t0", "whisper_vad_segments_get_segment_t1",
    "whisper_vad_free_segments", "whisper_vad_free",
)


class FixtureError(ValueError):
    pass


def download_verified(url, size, digest):
    request = urllib.request.Request(url, headers={"User-Agent": "Varta-native-fixtures/1"})
    with urllib.request.urlopen(request, timeout=30) as response:
        data = response.read(size + 1)
    if len(data) != size or hashlib.sha256(data).hexdigest() != digest:
        raise FixtureError("download size or SHA256 differs: " + url.split("/")[-1])
    return data


def inspect_model_header(data):
    if len(data) < 38:
        raise FixtureError("VAD model header is truncated")
    magic, length = struct.unpack_from("<ii", data)
    if magic != 0x67676D6C or length != 10 or data[8:18] != b"silero-16k":
        raise FixtureError("VAD model type differs")
    major, minor, patch_version, window, context = struct.unpack_from("<iiiii", data, 18)
    if (major, minor, patch_version, window, context) != (6, 2, 0, 512, 64):
        raise FixtureError("VAD model version/window/context differs")
    return {"model": "silero-16k", "version": "6.2.0", "window": window, "context": context}


def inspect_speech(data):
    with wave.open(io.BytesIO(data), "rb") as audio:
        if (audio.getnchannels(), audio.getsampwidth(), audio.getframerate(), audio.getnframes(), audio.getcomptype()) != (1, 2, 16000, 176000, "NONE"):
            raise FixtureError("speech fixture audio format differs")
    return {"sample_rate": 16000, "channels": 1, "frame_count": 176000}


def require_symbols(output):
    exported = {line.split()[-1] for line in output.splitlines() if line.split()}
    missing = [name for name in VAD_SYMBOLS if "_" + name not in exported]
    if missing:
        raise FixtureError("native framework lacks VAD exports: " + ", ".join(missing))
    return list(VAD_SYMBOLS)


def native_framework(config):
    helper_path = Path(__file__).with_name("prepare-whisper.py")
    spec = importlib.util.spec_from_file_location("varta_whisper_preparation", helper_path)
    helper = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(helper)
    config = helper.safe_path(config)
    text = config.read_text(encoding="utf-8")
    if not text.startswith(helper.MARKER):
        raise FixtureError("native configuration is not generated by the preparation helper")
    roots = [line.partition(" = ")[2] for line in text.splitlines() if line.startswith("VARTA_WHISPER_XCFRAMEWORK = ")]
    if len(roots) != 1:
        raise FixtureError("native configuration lacks one verified artifact root")
    root = helper.safe_path(roots[0])
    framework = helper.select_framework(root)
    if framework is None:
        raise FixtureError("real whisper.cpp framework is required for native VAD tests")
    return root, framework


def prepare(output, config):
    if os.environ.get("GITHUB_ACTIONS") != "true":
        raise FixtureError("VAD fixture downloads are restricted to the CI runner")
    output = Path(output).absolute()
    if output.exists() or output.is_symlink():
        raise FixtureError("choose a fresh VAD fixture output directory")
    root, framework = native_framework(config)
    if output.resolve() == root or root in output.resolve().parents:
        raise FixtureError("fixture output must lie outside the source framework artifact")
    probe = subprocess.run(["nm", "-arch", "arm64", "-gU", str(framework / "whisper")],
                           check=True, capture_output=True, text=True, timeout=20)
    symbols = require_symbols(probe.stdout)
    assets = {name: download_verified(url, size, digest) for name, url, size, digest in ASSETS}
    model_header = inspect_model_header(assets[MODEL_NAME])
    speech = inspect_speech(assets["jfk.wav"])
    manifest = {
        "model_header": model_header, "speech": speech, "native_vad_exports": symbols,
        "assets": [{"name": name, "url": url, "size": size, "sha256": digest} for name, url, size, digest in ASSETS],
        "model_card": f"https://huggingface.co/ggml-org/whisper-vad/blob/{MODEL_REVISION}/README.md",
        "model_licence": "MIT",
        "audio_provenance": "Official whisper.cpp pinned samples/jfk.wav; repository MIT notice retained. Upstream samples README supplies no separate recording licence.",
        "scope": "Native VAD execution fixtures; no ASR/LLM weights or audio-quality certification.",
    }
    output.mkdir(parents=True)
    for name, data in assets.items():
        with (output / name).open("xb") as stream:
            stream.write(data)
    with (output / "fixture-manifest.json").open("x", encoding="utf-8") as stream:
        json.dump(manifest, stream, indent=2)
        stream.write("\n")
    print(f"VAD fixtures verified: {MODEL_SIZE} model bytes, {SPEECH_SIZE} speech bytes, {len(symbols)} native exports")


class FixtureChecks(unittest.TestCase):
    def test_model_header_is_exact(self):
        header = struct.pack("<ii", 0x67676D6C, 10) + b"silero-16k" + struct.pack("<iiiii", 6, 2, 0, 512, 64)
        self.assertEqual(inspect_model_header(header)["window"], 512)
        for malformed in (header[:37], header[:30] + struct.pack("<i", 256) + header[34:], b"bad!" + header[4:]):
            with self.assertRaises(FixtureError):
                inspect_model_header(malformed)

    def test_download_size_and_checksum_are_bounded(self):
        data = b"fixture"
        digest = hashlib.sha256(data).hexdigest()
        with patch("urllib.request.urlopen", return_value=io.BytesIO(data)):
            self.assertEqual(download_verified("https://example.invalid/fixture", len(data), digest), data)
        for malformed in (data + b"extra", data[:-1], b"changed"):
            with patch("urllib.request.urlopen", return_value=io.BytesIO(malformed)):
                with self.assertRaises(FixtureError):
                    download_verified("https://example.invalid/fixture", len(data), digest)

    def test_all_native_vad_exports_are_required(self):
        output = "\n".join("000 T _" + name for name in VAD_SYMBOLS)
        self.assertEqual(len(require_symbols(output)), 13)
        with self.assertRaises(FixtureError):
            require_symbols(output.replace("_whisper_vad_detect_speech", "_different_symbol"))

    def test_speech_fixture_format_and_frame_identity(self):
        def fixture(rate, channels, frames):
            stream = io.BytesIO()
            with wave.open(stream, "wb") as audio:
                audio.setnchannels(channels)
                audio.setsampwidth(2)
                audio.setframerate(rate)
                audio.writeframes(b"\0\0" * channels * frames)
            return stream.getvalue()
        self.assertEqual(inspect_speech(fixture(16000, 1, 176000))["frame_count"], 176000)
        for malformed in (fixture(8000, 1, 176000), fixture(16000, 2, 176000), fixture(16000, 1, 175999)):
            with self.assertRaises(FixtureError):
                inspect_speech(malformed)

    def test_downloads_are_refused_outside_ci(self):
        with patch.dict(os.environ, {"GITHUB_ACTIONS": "false"}):
            with self.assertRaises(FixtureError):
                prepare("unused-fixture-output", "unused-native-config")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-directory", type=Path)
    parser.add_argument("--prepared-config", type=Path)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        result = unittest.TextTestRunner(verbosity=2).run(unittest.defaultTestLoader.loadTestsFromTestCase(FixtureChecks))
        return 0 if result.wasSuccessful() else 1
    if args.output_directory is None or args.prepared_config is None:
        parser.error("--output-directory and --prepared-config are required")
    try:
        prepare(args.output_directory, args.prepared_config)
    except (FixtureError, OSError, ValueError, subprocess.SubprocessError, wave.Error) as error:
        print("error: " + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
