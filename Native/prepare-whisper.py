#!/usr/bin/env python3
"""Prepare optional whisper.cpp linking/embedding without changing its artifact.

Upstream v1.8.3 builds a dynamic framework by default, with a static opt-in:
https://github.com/ggml-org/whisper.cpp/blob/v1.8.3/build-xcframework.sh
Its modulemap links system libraries but omits whisper itself; link explicitly.
Mach-O/fat header definitions:
https://github.com/apple-oss-distributions/cctools/blob/main/include/mach-o/loader.h
https://github.com/apple-oss-distributions/cctools/blob/main/include/mach-o/fat.h
"""

import argparse
import hashlib
import os
import plistlib
import shutil
import stat
import struct
import sys
import zipfile
from pathlib import Path


MARKER = "// Generated by Native/prepare-whisper.py. Do not edit.\n"
ARM64 = 0x0100000C


class PreparationError(ValueError):
    pass


def safe_path(value):
    for text in (str(value), str(Path(value).resolve())):
        if any(ord(character) < 32 or ord(character) == 127 for character in text) or any(
            character in text for character in '$"\\*#'
        ):
            raise PreparationError("path contains unsupported xcconfig metacharacters")
    return Path(value).resolve()


def inside(path, root):
    return path == root or root in path.parents


def artifact_path(root, *parts):
    for part in parts:
        if not isinstance(part, str) or not part or Path(part).is_absolute() or ".." in Path(part).parts:
            raise PreparationError("artifact metadata must use non-traversing relative paths")
    path = safe_path(root.joinpath(*parts))
    if not inside(path, root):
        raise PreparationError("artifact path escapes the XCFramework")
    return path


def slice_kind(stream, offset, size, expected_cpu):
    stream.seek(offset)
    header = stream.read(min(32, size))
    if header.startswith(b"!<arch>\n"):
        return "static"
    formats = {b"\xce\xfa\xed\xfe": ("<", 28), b"\xcf\xfa\xed\xfe": ("<", 32),
               b"\xfe\xed\xfa\xce": (">", 28), b"\xfe\xed\xfa\xcf": (">", 32)}
    if header[:4] not in formats:
        raise PreparationError("framework binary is not an ar archive or supported Mach-O")
    endian, minimum = formats[header[:4]]
    if len(header) < minimum:
        raise PreparationError("truncated Mach-O header")
    cpu, _, filetype = struct.unpack(endian + "III", header[4:16])
    if cpu != expected_cpu:
        raise PreparationError("Mach-O architecture disagrees with its slice metadata")
    if filetype not in (1, 6):
        raise PreparationError("framework Mach-O must be an object or dynamic library")
    return "dynamic" if filetype == 6 else "static"


def binary_kind(binary):
    size = binary.stat().st_size
    with binary.open("rb") as stream:
        prefix = stream.read(8)
        fat_formats = {b"\xca\xfe\xba\xbe": (">", False), b"\xbe\xba\xfe\xca": ("<", False),
                       b"\xca\xfe\xba\xbf": (">", True), b"\xbf\xba\xfe\xca": ("<", True)}
        if prefix[:4] not in fat_formats:
            return slice_kind(stream, 0, size, ARM64)
        if len(prefix) != 8:
            raise PreparationError("truncated universal Mach-O header")
        endian, wide = fat_formats[prefix[:4]]
        count = struct.unpack(endian + "I", prefix[4:])[0]
        if not 1 <= count <= 32:
            raise PreparationError("invalid universal Mach-O architecture count")
        record_size = 32 if wide else 20
        header_size = 8 + count * record_size
        table = stream.read(count * record_size)
        if len(table) != count * record_size:
            raise PreparationError("truncated universal Mach-O slice table")
        cpus, spans, kinds = set(), [], set()
        for index in range(count):
            record = table[index * record_size:(index + 1) * record_size]
            values = struct.unpack(endian + ("IIQQII" if wide else "IIIII"), record)
            cpu, _, offset, length = values[:4]
            if cpu in cpus or length < 4 or offset < header_size or offset + length > size:
                raise PreparationError("invalid universal Mach-O slice bounds or duplicate architecture")
            if any(offset < end and offset + length > start for start, end in spans):
                raise PreparationError("overlapping universal Mach-O slices")
            cpus.add(cpu)
            spans.append((offset, offset + length))
            kinds.add(slice_kind(stream, offset, length, cpu))
        if ARM64 not in cpus or len(kinds) != 1:
            raise PreparationError("universal framework needs arm64 and consistent static/dynamic slices")
        return kinds.pop()


def select_framework(root):
    if not root.exists():
        return None
    if not root.is_dir():
        raise PreparationError("XCFramework path is not a directory")
    info = artifact_path(root, "Info.plist")
    with info.open("rb") as stream:
        metadata = plistlib.load(stream)
    libraries = metadata.get("AvailableLibraries") if isinstance(metadata, dict) else None
    if not isinstance(libraries, list):
        raise PreparationError("XCFramework Info.plist lacks an AvailableLibraries array")
    if not libraries:
        return None
    candidates = []
    for library in libraries:
        if not isinstance(library, dict):
            raise PreparationError("XCFramework library metadata is not a dictionary")
        identifier, library_path = library.get("LibraryIdentifier"), library.get("LibraryPath")
        path = artifact_path(root, identifier, library_path)
        architectures = library.get("SupportedArchitectures")
        platform = library.get("SupportedPlatform")
        if not isinstance(architectures, list) or not architectures or not all(isinstance(cpu, str) for cpu in architectures) or not isinstance(platform, str):
            raise PreparationError("XCFramework library lacks platform/architecture metadata")
        if platform == "macos" and "arm64" in architectures and not library.get("SupportedPlatformVariant"):
            candidates.append(path)
    if len(candidates) != 1:
        raise PreparationError("expected exactly one native macOS arm64 XCFramework slice")
    framework = candidates[0]
    if framework.name != "whisper.framework" or not framework.is_dir():
        raise PreparationError("selected slice does not contain whisper.framework")
    for directory, names, files in os.walk(framework, followlinks=False):
        for name in names + files:
            path = Path(directory) / name
            if path.is_symlink() and os.path.isabs(os.readlink(path)):
                raise PreparationError("framework symlinks must be relative for portable embedding")
            if not inside(path.resolve(strict=True), root):
                raise PreparationError("framework symlink escapes the XCFramework")
    for relative in ("whisper", "Headers/whisper.h", "Modules/module.modulemap"):
        if not (framework / relative).is_file():
            raise PreparationError("framework is missing " + relative)
    return framework


def same_tree(source, destination):
    if source.is_symlink() or destination.is_symlink():
        return source.is_symlink() and destination.is_symlink() and os.readlink(source) == os.readlink(destination)
    if source.is_dir() and destination.is_dir():
        names = {path.name for path in source.iterdir()}
        return names == {path.name for path in destination.iterdir()} and all(
            same_tree(source / name, destination / name) for name in names
        )
    if source.is_file() and destination.is_file():
        if source.stat().st_size != destination.stat().st_size:
            return False
        with source.open("rb") as left, destination.open("rb") as right:
            while True:
                chunk = left.read(1024 * 1024)
                if chunk != right.read(1024 * 1024):
                    return False
                if not chunk:
                    return True
    return False


def extract_archive(archive, expected_sha256, destination):
    archive, destination = safe_path(archive), safe_path(destination)
    if destination.exists() or destination.is_symlink():
        raise PreparationError("archive extraction requires a fresh output directory")
    digest = hashlib.sha256()
    with archive.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    if len(expected_sha256) != 64 or digest.hexdigest() != expected_sha256.lower():
        raise PreparationError("archive SHA256 checksum mismatch")
    with zipfile.ZipFile(archive) as stream:
        members = stream.infolist()
        if len(members) > 10000 or sum(member.file_size for member in members) > 512 * 1024 * 1024:
            raise PreparationError("archive exceeds bounded extraction limits")
        entries, links, names = [], {}, set()
        for member in members:
            path = artifact_path(destination, member.filename)
            if path == destination or path in names:
                raise PreparationError("archive contains duplicate or empty member paths")
            names.add(path)
            mode = member.external_attr >> 16
            if stat.S_IFMT(mode) not in (0, stat.S_IFREG, stat.S_IFDIR, stat.S_IFLNK):
                raise PreparationError("archive contains unsupported special files")
            if stat.S_ISLNK(mode):
                if member.file_size > 4096:
                    raise PreparationError("archive symlink target is too long")
                target = stream.read(member).decode("utf-8")
                if Path(target).is_absolute() or not inside(safe_path(path.parent / target), destination):
                    raise PreparationError("archive symlink escapes its extraction directory")
                links[path] = target
            entries.append((member, path, mode))
        if any(any(parent in links for parent in path.parents) for _, path, _ in entries):
            raise PreparationError("archive members cannot be nested inside a symlink")
        destination.mkdir(parents=True)
        for member, path, mode in entries:
            if path in links:
                continue
            if member.is_dir() or stat.S_ISDIR(mode):
                path.mkdir(parents=True, exist_ok=True)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                with stream.open(member) as source, path.open("xb") as output:
                    shutil.copyfileobj(source, output, 1024 * 1024)
                if mode & 0o777:
                    path.chmod(mode & 0o777)
        for path, target in links.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.symlink_to(target)
        if any(not inside(path.resolve(strict=True), destination) for path in links):
            raise PreparationError("archive symlink chain escapes its extraction directory")
    frameworks = [path for path in destination.rglob("*.xcframework") if path.is_dir()]
    if len(frameworks) != 1:
        raise PreparationError("archive must contain exactly one XCFramework")
    return frameworks[0]


def prepare(xcframework, config_output, embed_directory=None, write_config=True):
    for value in (xcframework, config_output, embed_directory):
        if value is not None and Path(value).is_symlink():
            raise PreparationError("CLI artifact/output paths must not themselves be symlinks")
    root, config = safe_path(xcframework), safe_path(config_output)
    embed = safe_path(embed_directory) if embed_directory is not None else None
    if inside(config, root) or embed is not None and inside(embed, root):
        raise PreparationError("generated outputs must remain outside the source XCFramework")
    destination = embed / "whisper.framework" if embed is not None else None
    if destination is not None and inside(config, destination):
        raise PreparationError("xcconfig must remain outside the embedded framework")
    if config.exists() and (not config.is_file() or config.stat().st_nlink != 1 or not config.read_text().startswith(MARKER)):
        raise PreparationError("refusing to overwrite a configuration not generated by this tool")
    framework = select_framework(root)
    kind = binary_kind(framework / "whisper") if framework is not None else "unavailable"
    if kind == "dynamic" and destination is not None:
        if destination.is_symlink() or destination.exists() and not same_tree(framework, destination):
            raise PreparationError("embed destination differs; choose a fresh generated output directory")
        if not destination.exists():
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(framework, destination, symlinks=True)
    content = MARKER + "VARTA_WHISPER_XCFRAMEWORK = " + str(root) + "\nFRAMEWORK_SEARCH_PATHS = $(inherited)"
    if framework is not None:
        content += ' "' + str(framework.parent) + '"'
    content += "\nOTHER_LDFLAGS = $(inherited)"
    if framework is not None:
        content += " -framework whisper"
    content += "\n"
    if write_config:
        config.parent.mkdir(parents=True, exist_ok=True)
    if write_config and (not config.exists() or config.read_text() != content):
        flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC | getattr(os, "O_NOFOLLOW", 0)
        with os.fdopen(os.open(config, flags, 0o644), "w") as stream:
            stream.write(content)
    return kind


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--xcframework", type=Path)
    source.add_argument("--archive", type=Path)
    source.add_argument("--prepared-config", type=Path)
    parser.add_argument("--config-output", type=Path)
    parser.add_argument("--sha256")
    parser.add_argument("--extract-directory", type=Path)
    parser.add_argument("--embed-directory", type=Path)
    args = parser.parse_args()
    try:
        if args.prepared_config:
            config = safe_path(args.prepared_config)
            content = config.read_text()
            roots = [line.partition(" = ")[2] for line in content.splitlines() if line.startswith("VARTA_WHISPER_XCFRAMEWORK = ")]
            if not content.startswith(MARKER) or len(roots) != 1:
                raise PreparationError("prepared configuration is not generated by this tool")
            kind = prepare(Path(roots[0]), config, args.embed_directory, write_config=False)
            args.config_output = config
        else:
            if args.config_output is None:
                parser.error("--config-output is required for preparation")
            if args.archive:
                if not args.sha256 or args.extract_directory is None:
                    parser.error("--archive requires --sha256 and --extract-directory")
                args.xcframework = extract_archive(args.archive, args.sha256, args.extract_directory)
            kind = prepare(args.xcframework, args.config_output, args.embed_directory)
    except (OSError, ValueError, RuntimeError, plistlib.InvalidFileException, struct.error, zipfile.BadZipFile) as error:
        print("error: " + str(error), file=sys.stderr)
        return 2
    print("whisper: " + kind + "; configuration: " + str(args.config_output))
    return 0


if __name__ == "__main__":
    sys.exit(main())
